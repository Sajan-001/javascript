// Q19 — printNumbers(limit)
function printNumbers(limit) {
    for (let i = 1; i <= limit; i++) {
        console.log(i);
    }
}

printNumbers(5);


// Q20 — printEvenNumbers(limit)
function printEvenNumbers(limit) {
    for (let i = 2; i <= limit; i += 2) {
        console.log(i);
    }
}

printEvenNumbers(20);