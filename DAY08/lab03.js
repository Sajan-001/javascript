// 1. Print 1 → 20
for (let i = 1; i <= 20; i++) {
    console.log(i);
}


// 2. Print 20 → 1
for (let i = 20; i >= 1; i--) {
    console.log(i);
}


// 3. Print odd numbers 1 → 25
for (let i = 1; i <= 25; i += 2) {
    console.log(i);
}


// 4. Print even numbers 2 → 30
for (let i = 2; i <= 30; i += 2) {
    console.log(i);
}


// 5. Print multiples of 7, 7 → 70
for (let i = 7; i <= 70; i += 7) {
    console.log(i);
}


// 6. Print squares 1² → 10²
for (let i = 1; i <= 10; i++) {
    console.log(i * i);
}