// 1. Print 1 → 5
let i = 1;

do {
    console.log(i);
    i++;
} while (i <= 5);


// 2. Print 10 → 1
i = 10;

do {
    console.log(i);
    i--;
} while (i >= 1);


// 3. Print even numbers 2 → 20
i = 2;

do {
    console.log(i);
    i += 2;
} while (i <= 20);


