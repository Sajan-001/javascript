// Declaring variables using let
let userName = "Sajan Kumar";
let userAge = 23;
let userCity = "Kolkata";

// Printing variables
console.log("Name:", userName);
console.log("Age:", userAge);
console.log("City:", userCity);

// Demonstrating that a let variable can be updated
let score = 50;
console.log("Score:", score);

score = 90;
console.log("Updated Score:", score);

// Declaring a constant variable
const country = "India";

// Country should NOT change because it is a constant value.
console.log("Country:", country);