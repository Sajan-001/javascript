let day = "Monday";

switch (day) {
    case "Monday":
        console.log("New Week Started");
        break;

    case "Tuesday":
        console.log("Keep Learning");
        break;

    case "Wednesday":
        console.log("Half Week");
        break;

    case "Thursday":
        console.log("Almost There");
        break;

    case "Friday":
        console.log("Project Day");
        break;

    case "Saturday":
        console.log("Revision Day");
        break;

    case "Sunday":
        console.log("Rest & Recharge");
        break;

    default:
        console.log("Invalid Day");
}